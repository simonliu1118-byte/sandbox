const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../App/travel_memory/resources/Map/index.html'), 'utf8');
const source = html.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
const element = () => ({style:{},clientWidth:800,clientHeight:600,appendChild(){},setAttribute(){},addEventListener(){},remove(){}});
const context = vm.createContext({console, document:{getElementById:element,createElement:element,createElementNS:element},qt:{webChannelTransport:{}},QWebChannel:function(){},setTimeout(){},setInterval(){},clearInterval(){},clearTimeout(){}});
vm.runInContext('window=globalThis', context);
vm.runInContext(source, context);
vm.runInContext(`
  calls=[]; loaded=true;
  map={isStyleLoaded:()=>loaded,getSource:()=>({setData(){}}),getLayer:()=>false,stop(){},fitBounds:(b,o)=>calls.push({b,o}),jumpTo:o=>calls.push({point:o})};
  window.tmSetTracks({tracks:[{id:1,bounds:[130,30,142,40],segments:[{points:[{lon:131,lat:31},{lon:141,lat:39}]}]}],fit:true});
`, context);
assert.equal(vm.runInContext('calls.length',context),1,'first fit');
vm.runInContext('renderOnline();window.tmSetOptions({showPoints:false});window.tmSetTracks({...payload,fit:false})',context);
assert.equal(vm.runInContext('calls.length',context),1,'redraw never fits');
vm.runInContext('loaded=false;fitAllTracks();cancelViewport();loaded=true;renderOnline()',context);
assert.equal(vm.runInContext('calls.length',context),1,'cancel pending loading fit');
vm.runInContext('loaded=false;fitAllTracks();loaded=true;renderOnline();renderOnline()',context);
assert.equal(vm.runInContext('calls.length',context),2,'delayed fit consumed once');
vm.runInContext('window.tmFitTrack(1,[135,35,136,36]);renderOnline()',context);
assert.equal(vm.runInContext('calls.length',context),3,'target fit once');
assert.equal(vm.runInContext('JSON.stringify(calls[2].b)',context),'[[135,35],[136,36]]');
vm.runInContext('window.tmFitTrack(2,[135,35,135,35])',context);
assert.equal(vm.runInContext('calls[3].point.zoom',context),14,'single point bounded zoom');
vm.runInContext('window.tmFitTrack(99,null);renderOnline()',context);
assert.equal(vm.runInContext('calls.length',context),4,'empty bounds no camera change');
assert.match(html,/maplibregl-ctrl-group button\.tm-control-button\{display:flex;align-items:center;justify-content:center/);
console.log('PASS viewport: one-shot, redraw preservation, loading cancel, targeted bounds, single point, empty track, centering rule');
